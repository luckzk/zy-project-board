"""SQLAlchemy models for zy-project-board backend."""
from sqlalchemy import Boolean, Column, DateTime, ForeignKey, Integer, String, Text, UniqueConstraint

from app.database import Base


class Project(Base):
    """A project (kanban board scope). Seeded from seed.PROJECTS on
    first start; created/renamed/deleted via the API afterwards.
    Tickets reference projects by this id string."""

    __tablename__ = "projects"

    id = Column(String(64), primary_key=True)
    name = Column(String(128), nullable=False)
    created_at = Column(DateTime, nullable=False)


class ProjectMember(Base):
    """Membership of a login account in a project (round 13).

    Only members can see a project's tickets and comment on them;
    role is ``member`` for now (a single value, kept for later
    roles such as admin). (project_id, account_id) is unique.
    """

    __tablename__ = "project_members"
    __table_args__ = (UniqueConstraint("project_id", "account_id"),)

    id = Column(Integer, primary_key=True, index=True)
    project_id = Column(String(64), ForeignKey("projects.id"), nullable=False, index=True)
    account_id = Column(Integer, ForeignKey("accounts.id"), nullable=False, index=True)
    role = Column(String(32), nullable=False, default="member")
    created_at = Column(DateTime, nullable=False)


class Ticket(Base):
    __tablename__ = "tickets"

    id = Column(Integer, primary_key=True, index=True)
    code = Column(String(32), unique=True, nullable=False, index=True)
    category = Column(String(128), nullable=False, default="")
    title = Column(String(512), nullable=False)
    description = Column(Text, nullable=False, default="")
    status = Column(String(32), nullable=False, default="todo", index=True)
    priority = Column(String(32), nullable=False, default="low")
    project_id = Column(String(64), nullable=False, default="p-boardui", index=True)
    # JSON-encoded list of user ids, e.g. '["u-maya", "u-priya"]'
    assignee_ids = Column(Text, nullable=False, default="[]")
    # Display name of the account that created the ticket (JWT account
    # name, or the passed author / "API" for API-Key calls). NULL for
    # tickets created before this field existed — the drawer hides the
    # "Created by" row rather than inventing a creator.
    created_by = Column(String(128), nullable=True)
    # Starred from the drawer header; persisted, not local state.
    is_favorite = Column(Boolean, nullable=False, default=False)
    created_at = Column(DateTime, nullable=False)
    updated_at = Column(DateTime, nullable=False)
    completed_at = Column(DateTime, nullable=True)
    position = Column(Integer, nullable=False, default=0)


class Notification(Base):
    """A bell notification, generated by real board events (never demo data).

    type: ``ticket`` (created / moved / commented), ``mention`` (newly
    assigned to a ticket) or ``system`` (e.g. a user sync). actor_name
    is the display name shown with the notification (comment author,
    newly assigned person, ...); ticket_id links to the drawer.
    """

    __tablename__ = "notifications"

    id = Column(Integer, primary_key=True, index=True)
    type = Column(String(32), nullable=False, default="ticket", index=True)
    title = Column(String(512), nullable=False)
    description = Column(Text, nullable=False, default="")
    ticket_id = Column(Integer, ForeignKey("tickets.id"), nullable=True, index=True)
    actor_name = Column(String(128), nullable=True)
    is_read = Column(Boolean, nullable=False, default=False, index=True)
    created_at = Column(DateTime, nullable=False)


class Comment(Base):
    __tablename__ = "comments"

    id = Column(Integer, primary_key=True, index=True)
    ticket_id = Column(Integer, ForeignKey("tickets.id"), nullable=False, index=True)
    author_id = Column(String(64), nullable=False)
    author_name = Column(String(128), nullable=False)
    body = Column(Text, nullable=False)
    created_at = Column(DateTime, nullable=False)


class Account(Base):
    """A login account (register/login), separate from directory users."""

    __tablename__ = "accounts"

    id = Column(Integer, primary_key=True, index=True)
    name = Column(String(128), nullable=False)
    email = Column(String(256), unique=True, nullable=False, index=True)
    password_hash = Column(String(256), nullable=False)
    created_at = Column(DateTime, nullable=False)


class DirectoryUser(Base):
    """A person in the mock people directory.

    Seed users come from seed.py; external platforms sync in via
    POST /api/users/sync, keyed by (source, external_id).
    """

    __tablename__ = "directory_users"
    __table_args__ = (UniqueConstraint("source", "external_id"),)

    id = Column(String(64), primary_key=True)
    name = Column(String(128), nullable=False)
    email = Column(String(256), nullable=False, default="")
    role = Column(String(128), nullable=False, default="")
    avatar_url = Column(String(512), nullable=False, default="")
    initials = Column(String(8), nullable=False, default="")
    color = Column(String(16), nullable=False, default="#737373")
    source = Column(String(64), nullable=False, default="seed", index=True)
    external_id = Column(String(128), nullable=False, default="")
    active = Column(Boolean, nullable=False, default=True)
    synced_at = Column(DateTime, nullable=True)
    sort_order = Column(Integer, nullable=False, default=0)
